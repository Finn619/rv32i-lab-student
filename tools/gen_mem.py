#!/usr/bin/env python3
"""gen_mem.py - turn a linked RV32I ELF into memory images (Lab 5).

Outputs (in --out-dir):
  NAME.imem.hex          one 32-bit little-endian word per line (simulation)
  NAME.dmem.hex          likewise for DMEM
  prog_image_body.vhd    package body of prog_image_pkg holding both images as
                         VHDL constants. This is the file synthesis uses: it
                         works unchanged in Vivado and Quartus, because inferred
                         RAM/ROM initial values come from VHDL default values.

Every PT_LOAD segment must lie entirely inside IMEM (0x0xxx_xxxx) or DMEM
(0x1xxx_xxxx). Bytes the ELF does not define are zero.
"""
import argparse
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile

IMEM_BASE, DMEM_BASE = 0x0000_0000, 0x1000_0000


def load_segments(elf_path):
    with open(elf_path, "rb") as f:
        elf = ELFFile(f)
        if elf["e_machine"] != "EM_RISCV" or elf.elfclass != 32:
            sys.exit(f"{elf_path}: not a 32-bit RISC-V ELF")
        segs = []
        for seg in elf.iter_segments():
            if seg["p_type"] != "PT_LOAD" or seg["p_memsz"] == 0:
                continue
            segs.append((seg["p_paddr"], seg.data(), seg["p_memsz"]))
        return segs, elf.header["e_entry"]


def build_images(segments, imem_bytes, dmem_bytes):
    images = {"imem": bytearray(), "dmem": bytearray()}
    for addr, data, memsz in segments:
        region = addr >> 28
        if region == 0:
            name, base, cap = "imem", IMEM_BASE, imem_bytes
        elif region == 1:
            name, base, cap = "dmem", DMEM_BASE, dmem_bytes
        else:
            sys.exit(f"segment at 0x{addr:08x} is outside IMEM and DMEM")
        off = addr - base
        if off + memsz > cap:
            sys.exit(f"{name} overflow: segment 0x{addr:08x}+{memsz} exceeds {cap} bytes")
        img = images[name]
        if len(img) < off + len(data):
            img.extend(bytes(off + len(data) - len(img)))
        img[off:off + len(data)] = data
    for img in images.values():
        img.extend(bytes(-len(img) % 4))
    return images


def words(img):
    return [int.from_bytes(img[i:i + 4], "little") for i in range(0, len(img), 4)]


def vhdl_constant(name, ws):
    if not ws:
        ws = [0]
    body = ",\n".join(
        "    " + ", ".join(f'{i + j} => x"{w:08x}"' for j, w in enumerate(ws[i:i + 4]))
        for i in range(0, len(ws), 4))
    return f"  constant {name} : image_t(0 to {len(ws) - 1}) := (\n{body}\n  );\n"


def write_vhdl(path, imem, dmem, source):
    path.write_text(f"""-------------------------------------------------------------------------------
-- prog_image_body.vhd - GENERATED by tools/gen_mem.py from {source}
-- Do not edit. Synthesis body of prog_image_pkg: the program as constants.
-------------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;

package body prog_image_pkg is

{vhdl_constant("IMEM_DATA", imem)}
{vhdl_constant("DMEM_DATA", dmem)}
  impure function region_image(region : natural; words : positive; init_file : string)
    return image_t is
    variable r : image_t(0 to words - 1) := (others => (others => '0'));
  begin
    if region = REGION_IMEM_ID then
      for i in IMEM_DATA'range loop
        if i < words then
          r(i) := IMEM_DATA(i);
        end if;
      end loop;
    else
      for i in DMEM_DATA'range loop
        if i < words then
          r(i) := DMEM_DATA(i);
        end if;
      end loop;
    end if;
    return r;
  end function;

end package body prog_image_pkg;
""")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("elf")
    ap.add_argument("--out-dir", default=".")
    ap.add_argument("--name", default=None, help="base name for the .hex files")
    ap.add_argument("--imem-bytes", type=int, default=32 * 1024, help="IMEM capacity (FPGA build)")
    ap.add_argument("--dmem-bytes", type=int, default=32 * 1024, help="DMEM capacity (FPGA build)")
    args = ap.parse_args()

    segs, entry = load_segments(args.elf)
    if entry != 0:
        sys.exit(f"entry point is 0x{entry:08x}; the reset vector is 0x00000000")
    imgs = build_images(segs, args.imem_bytes, args.dmem_bytes)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    name = args.name or Path(args.elf).stem
    for region in ("imem", "dmem"):
        with open(out / f"{name}.{region}.hex", "w") as f:
            for w in words(imgs[region]):
                f.write(f"{w:08x}\n")
    write_vhdl(out / "prog_image_body.vhd", words(imgs["imem"]), words(imgs["dmem"]),
               Path(args.elf).name)
    print(f"{name}: IMEM {len(imgs['imem'])} bytes, DMEM {len(imgs['dmem'])} bytes (initialised)")


if __name__ == "__main__":
    main()
